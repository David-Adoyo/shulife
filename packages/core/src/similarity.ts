/** String similarity helpers used for name matching. */

export function jaroWinkler(a: string, b: string): number {
  if (a === b) return a.length ? 1 : 0;
  if (!a.length || !b.length) return 0;
  const range = Math.max(0, Math.floor(Math.max(a.length, b.length) / 2) - 1);
  const am = new Array(a.length).fill(false);
  const bm = new Array(b.length).fill(false);
  let matches = 0;
  for (let i = 0; i < a.length; i++) {
    for (let j = Math.max(0, i - range); j < Math.min(b.length, i + range + 1); j++) {
      if (bm[j] || a[i] !== b[j]) continue;
      am[i] = bm[j] = true;
      matches++;
      break;
    }
  }
  if (!matches) return 0;
  let t = 0;
  for (let i = 0, k = 0; i < a.length; i++) {
    if (!am[i]) continue;
    while (!bm[k]) k++;
    if (a[i] !== b[k]) t++;
    k++;
  }
  const jaro = (matches / a.length + matches / b.length + (matches - t / 2) / matches) / 3;
  let prefix = 0;
  while (prefix < 4 && a[prefix] === b[prefix]) prefix++;
  return jaro + prefix * 0.1 * (1 - jaro);
}

export function levenshtein(a: string, b: string): number {
  const dp = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    let prev = dp[0];
    dp[0] = i;
    for (let j = 1; j <= b.length; j++) {
      const tmp = dp[j];
      dp[j] = Math.min(dp[j] + 1, dp[j - 1] + 1, prev + (a[i - 1] === b[j - 1] ? 0 : 1));
      prev = tmp;
    }
  }
  return dp[b.length];
}

export function nameTokens(name: string): string[] {
  return name
    .toUpperCase()
    .split(/[^A-Z']+/)
    .map((t) => t.replace(/'/g, ""))
    .filter((t) => t.length >= 2);
}

/**
 * Order-tolerant name similarity (Kenyan names are often written surname first,
 * or with only one of several names). For each token of the shorter name, take the
 * best Jaro-Winkler against the other name's tokens, then average.
 */
export function nameSimilarity(a: string | string[], b: string | string[]): number {
  const ta = Array.isArray(a) ? a : nameTokens(a);
  const tb = Array.isArray(b) ? b : nameTokens(b);
  if (!ta.length || !tb.length) return 0;
  const [short, long] = ta.length <= tb.length ? [ta, tb] : [tb, ta];
  const scores = short.map((s) => Math.max(...long.map((l) => jaroWinkler(s, l))));
  return scores.reduce((x, y) => x + y, 0) / scores.length;
}
